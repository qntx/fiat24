/// <reference types="node" />
import { spawnSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { getAddress } from "viem";

const ROOT = join(import.meta.dirname, "..");
const ABI_SRC = join(ROOT, "data", "abis");
const ABI_DIR = join("packages", "fiat24", "src", "abi");
const DEPLOYMENTS_DIR = join("packages", "fiat24", "src", "deployments");
const CHECK = process.argv.includes("--check");

const MARKER = "// Generated by scripts/gen.ts — do not edit.";

type GeneratedFile = { path: string; content: string };

// One module per verified ABI in data/abis (see data/SOURCE.md); the table is
// explicit so a stray fetch output can never land in src unnoticed.
const ABIS: ReadonlyArray<readonly [module: string, source: string, exportName: string]> = [
  ["account", "Fiat24Account.json", "accountAbi"],
  ["token", "Fiat24Token.json", "tokenAbi"],
  ["deposit", "Fiat24CryptoDeposit.json", "depositAbi"],
  ["card", "Fiat24CardAuthorizationMarqeta.json", "cardAbi"],
  ["price-list", "Fiat24PriceList.json", "priceListAbi"],
  ["f24-sales", "F24Sales.json", "f24SalesAbi"],
  ["f24", "F24.json", "f24Abi"],
  ["proxy-admin", "ProxyAdmin.json", "proxyAdminAbi"],
];

function readData(path: string): unknown {
  return JSON.parse(readFileSync(join(ROOT, "data", path), "utf8"));
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function abiModules(): GeneratedFile[] {
  // The table and the directory must describe exactly the same set of files.
  const onDisk = new Set(
    readdirSync(ABI_SRC, { withFileTypes: true })
      .filter((entry) => entry.isFile() && entry.name.endsWith(".json"))
      .map((entry) => entry.name),
  );
  const expected = new Set(ABIS.map(([, source]) => source));
  for (const file of onDisk) {
    if (!expected.has(file)) {
      throw new Error(`data/abis/${file}: not in the gen.ts ABI table`);
    }
  }
  for (const [, source] of ABIS) {
    if (!onDisk.has(source)) {
      throw new Error(`data/abis/${source}: missing (expected by the gen.ts ABI table)`);
    }
  }

  // src/abi/errors.ts bundles every custom error of the eight ABIs so
  // core/revert.ts can decode any revert selector without importing them all.
  const errors: Array<Record<string, unknown>> = [];
  const seenErrors = new Set<string>();
  const modules: GeneratedFile[] = [];
  const exports: string[] = [];
  for (const [module, source, exportName] of ABIS) {
    const abi: unknown = readData(join("abis", source));
    if (!Array.isArray(abi)) {
      throw new TypeError(`data/abis/${source}: expected a JSON array`);
    }
    for (const entry of abi) {
      if (isRecord(entry) && entry["type"] === "error") {
        const signature = JSON.stringify(entry);
        if (!seenErrors.has(signature)) {
          seenErrors.add(signature);
          errors.push(entry);
        }
      }
    }
    modules.push({
      path: join(ABI_DIR, `${module}.ts`),
      content:
        `${MARKER}\n` +
        `// Source: data/abis/${source} (see data/SOURCE.md).\n` +
        `export const ${exportName} = ${JSON.stringify(abi, null, 2)} as const;\n`,
    });
    exports.push(`export { ${exportName} } from "./${module}.ts";`);
  }
  errors.sort((a, b) => {
    const left = String(a["name"]);
    const right = String(b["name"]);
    if (left !== right) {
      return left < right ? -1 : 1;
    }
    const leftJson = JSON.stringify(a);
    const rightJson = JSON.stringify(b);
    return leftJson < rightJson ? -1 : leftJson > rightJson ? 1 : 0;
  });
  modules.push(
    {
      path: join(ABI_DIR, "errors.ts"),
      content:
        `${MARKER}\n` +
        `// Source: data/abis/*.json — every "error" entry, deduplicated and sorted by name.\n` +
        `export const fiat24ErrorsAbi = ${JSON.stringify(errors, null, 2)} as const;\n`,
    },
    {
      path: join(ABI_DIR, "index.ts"),
      content: `${MARKER}\n${exports.join("\n")}\nexport { fiat24ErrorsAbi } from "./errors.ts";\n`,
    },
  );
  return modules;
}

const ADDRESS_RE = /^0x[0-9a-fA-F]{40}$/;
const HASH_RE = /^0x[0-9a-f]{64}$/;

// Walks the whole deployments.json: every 0x+40 value must already be the
// EIP-55 form (getAddress is the identity on it), every 0x+64 value lowercase.
// A non-canonical pin is a generator failure, never silently emitted.
function validateHexStrings(value: unknown, path: string): void {
  if (typeof value === "string") {
    if (ADDRESS_RE.test(value)) {
      if (value !== getAddress(value)) {
        throw new Error(`data/deployments.json: ${path} is not EIP-55 (${value})`);
      }
      return;
    }
    if (value.startsWith("0x") && !HASH_RE.test(value)) {
      throw new Error(`data/deployments.json: ${path} is not a lowercase 32-byte hash (${value})`);
    }
    return;
  }
  if (Array.isArray(value)) {
    for (const [index, item] of value.entries()) {
      validateHexStrings(item, `${path}[${index}]`);
    }
    return;
  }
  if (isRecord(value)) {
    for (const [key, item] of Object.entries(value)) {
      validateHexStrings(item, path === "" ? key : `${path}.${key}`);
    }
  }
}

const PROXY_NAMES = [
  "account",
  "USD24",
  "EUR24",
  "CHF24",
  "CNH24",
  "deposit",
  "card",
  "priceList",
  "f24Sales",
] as const;
const TOKEN_NAMES = ["USD24", "EUR24", "CHF24", "CNH24"] as const;

type JsonProxy = { proxy: string; implementation: string; codeHash: string; admin: string };

function readProxy(proxies: Record<string, unknown>, name: string): JsonProxy {
  const value = proxies[name];
  if (!isRecord(value)) {
    throw new Error(`data/deployments.json: proxies.${name} is missing`);
  }
  const keys = Object.keys(value).toSorted();
  const expectedKeys = ["admin", "codeHash", "implementation", "proxy"];
  if (JSON.stringify(keys) !== JSON.stringify(expectedKeys)) {
    throw new Error(
      `data/deployments.json: proxies.${name} keys must be ${expectedKeys.join(",")}`,
    );
  }
  return value as unknown as JsonProxy;
}

function deploymentsModule(): GeneratedFile {
  const data = readData("deployments.json");
  if (!isRecord(data)) {
    throw new TypeError("data/deployments.json: expected a JSON object");
  }
  validateHexStrings(data, "");
  if (data["chainId"] !== 42161) {
    throw new Error("data/deployments.json: chainId must be 42161");
  }
  const { block } = data;
  if (typeof block !== "string" || !/^(0|[1-9][0-9]*)$/.test(block)) {
    throw new Error("data/deployments.json: block must be a canonical decimal string");
  }
  const { proxies } = data;
  if (!isRecord(proxies)) {
    throw new Error("data/deployments.json: proxies must be an object");
  }
  const proxyKeys = Object.keys(proxies).toSorted();
  if (JSON.stringify(proxyKeys) !== JSON.stringify([...PROXY_NAMES].toSorted())) {
    throw new Error(`data/deployments.json: proxies must be exactly ${PROXY_NAMES.join(",")}`);
  }
  const { f24 } = data;
  const { usdc } = data;
  const { proxyAdmin } = data;
  if (!isRecord(f24) || typeof f24["address"] !== "string" || typeof f24["codeHash"] !== "string") {
    throw new Error("data/deployments.json: f24.address/codeHash are missing");
  }
  if (typeof usdc !== "string") {
    throw new TypeError("data/deployments.json: usdc is missing");
  }
  if (
    !isRecord(proxyAdmin) ||
    typeof proxyAdmin["address"] !== "string" ||
    typeof proxyAdmin["owner"] !== "string"
  ) {
    throw new Error("data/deployments.json: proxyAdmin.address/owner are missing");
  }

  const proxyLiteral = (name: string): string => {
    const { proxy, implementation, codeHash, admin } = readProxy(proxies, name);
    return `Object.freeze(${JSON.stringify({ proxy, implementation, codeHash, admin }, null, 2)})`;
  };
  const tokens = TOKEN_NAMES.map((name) => `${name}: ${proxyLiteral(name)},`).join("\n");
  // `monitor` and `proxyAdmin.codeHash` are verify.ts-only values (SPEC §4.1)
  // and are deliberately not generated into src.
  const content =
    `${MARKER}\n` +
    `// Source: data/deployments.json (read at block ${block}, see data/SOURCE.md).\n` +
    `import type { Deployment } from "./deployment.ts";\n\n` +
    // The pin is the security boundary: every object literal is frozen at
    // module load so a stray consumer cannot rewrite an address or hash.
    `export const arbitrum: Deployment = Object.freeze({\n` +
    `  chainId: 42161,\n` +
    `  block: ${block}n,\n` +
    `  account: ${proxyLiteral("account")},\n` +
    `  tokens: Object.freeze({\n${tokens}\n  }),\n` +
    `  deposit: ${proxyLiteral("deposit")},\n` +
    `  card: ${proxyLiteral("card")},\n` +
    `  priceList: ${proxyLiteral("priceList")},\n` +
    `  f24Sales: ${proxyLiteral("f24Sales")},\n` +
    `  f24: Object.freeze({ address: ${JSON.stringify(f24["address"])}, codeHash: ${JSON.stringify(f24["codeHash"])} }),\n` +
    `  usdc: ${JSON.stringify(usdc)},\n` +
    `  proxyAdmin: Object.freeze({\n` +
    `    address: ${JSON.stringify(proxyAdmin["address"])},\n` +
    `    owner: ${JSON.stringify(proxyAdmin["owner"])},\n` +
    `  }),\n` +
    `});\n`;
  return { path: join(DEPLOYMENTS_DIR, "data.ts"), content };
}

// Generated TypeScript goes through `vp fmt`, so generated output is already
// formatted and `bun run gen --check` agrees with `vp check`.
function format(path: string, content: string): string {
  const env = {
    ...process.env,
    PATH: `${join(ROOT, "node_modules/.bin")}:${process.env["PATH"] ?? ""}`,
  };
  const out = spawnSync("vp", ["fmt", `--stdin-filepath=${path}`], {
    cwd: ROOT,
    env,
    input: content,
    encoding: "utf8",
  });
  if (out.status !== 0 || out.stdout === "") {
    throw new Error(`vp fmt failed for ${path}: ${out.stderr}`);
  }
  return out.stdout;
}

if (import.meta.main) {
  const targets = [...abiModules(), deploymentsModule()];
  const expectedAbi = new Set(
    targets.map(({ path }) => path).filter((path) => path.startsWith(ABI_DIR)),
  );
  // A file under src/abi that gen did not produce is stale generated output
  // (the ABI was removed upstream) — write mode deletes it, check mode fails.
  const strays = existsSync(join(ROOT, ABI_DIR))
    ? readdirSync(join(ROOT, ABI_DIR), { withFileTypes: true })
        .filter((entry) => entry.isFile() && entry.name.endsWith(".ts"))
        .map((entry) => join(ABI_DIR, entry.name))
        .filter((path) => !expectedAbi.has(path))
    : [];
  let drift = false;
  for (const { path, content } of targets) {
    const formatted = format(path, content);
    const full = join(ROOT, path);
    const current = (() => {
      try {
        return readFileSync(full, "utf8");
      } catch {
        return "";
      }
    })();
    if (CHECK) {
      if (current !== formatted) {
        console.error(`gen: ${path} is out of date`);
        drift = true;
      }
    } else if (current !== formatted) {
      writeFileSync(full, formatted);
      console.log(`gen: wrote ${path}`);
    }
  }
  for (const stray of strays) {
    if (CHECK) {
      console.error(`gen: ${stray} is not produced by gen.ts`);
      drift = true;
    } else {
      rmSync(join(ROOT, stray));
      console.log(`gen: deleted stray ${stray}`);
    }
  }
  if (drift) {
    console.error("gen: run `bun run gen` to regenerate");
    process.exitCode = 1;
  }
}
