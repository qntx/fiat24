/// <reference types="node" />
import { spawnSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dirname, "..");
const ABI_SRC = join(ROOT, "data", "abis");
const ABI_DIR = join("packages", "fiat24", "src", "abi");
const CHECK = process.argv.includes("--check");

const MARKER = "// Generated by scripts/gen.ts — do not edit.";

type GeneratedFile = { path: string; content: string };

// data/abis/<kebab-name>.json → src/abi/<kebab-name>.ts exporting
// `export const <camelName>Abi = <abi> as const;`. The directory does not
// exist until the verified ABIs land in data/abis; with zero inputs the
// layer is just `export {};` so the build stays real.
function kebabToCamel(id: string): string {
  return id.replaceAll(/-[a-z0-9]/g, (pair) => pair.slice(1).toUpperCase());
}

function abiModules(): GeneratedFile[] {
  const names = existsSync(ABI_SRC)
    ? readdirSync(ABI_SRC, { withFileTypes: true })
        .filter((entry) => entry.isFile() && entry.name.endsWith(".json"))
        .map((entry) => entry.name.slice(0, -".json".length))
        .toSorted()
    : [];
  const modules: GeneratedFile[] = [];
  const exports: string[] = [];
  for (const name of names) {
    const source = join("abis", `${name}.json`);
    const abi: unknown = JSON.parse(readFileSync(join(ROOT, "data", source), "utf8"));
    if (!Array.isArray(abi)) {
      throw new TypeError(`data/${source}: expected a JSON array`);
    }
    const exportName = `${kebabToCamel(name)}Abi`;
    modules.push({
      path: join(ABI_DIR, `${name}.ts`),
      content:
        `${MARKER}\n` +
        `// Source: data/${source} (see data/SOURCE.md).\n` +
        `export const ${exportName} = ${JSON.stringify(abi, null, 2)} as const;\n`,
    });
    exports.push(`export { ${exportName} } from "./${name}.ts";`);
  }
  // The empty-module marker needs the disable comment: oxlint bans a bare
  // `export {};` (unicorn/require-module-specifiers).
  modules.push({
    path: join(ABI_DIR, "index.ts"),
    content:
      exports.length > 0
        ? `${MARKER}\n${exports.join("\n")}\n`
        : `${MARKER}\n` +
          `// oxlint-disable-next-line unicorn/require-module-specifiers -- empty until data/abis lands\n` +
          `export {};\n`,
  });
  return modules;
}

// Generated TypeScript goes through `vp fmt`, so generated output is already
// formatted and `bun run gen --check` agrees with `vp check`.
function format(path: string, content: string): string {
  const env = {
    ...process.env,
    PATH: `${join(ROOT, "node_modules/.bin")}:${process.env["PATH"] ?? ""}`,
  };
  const out = spawnSync("vp", ["fmt", `--stdin-filepath=${path}`], {
    cwd: ROOT,
    env,
    input: content,
    encoding: "utf8",
  });
  if (out.status !== 0 || out.stdout === "") {
    throw new Error(`vp fmt failed for ${path}: ${out.stderr}`);
  }
  return out.stdout;
}

if (import.meta.main) {
  const targets = abiModules();
  const expected = new Set(targets.map(({ path }) => path));
  // A file under src/abi that gen did not produce is stale generated output
  // (the ABI was removed upstream) — write mode deletes it, check mode fails.
  const strays = existsSync(join(ROOT, ABI_DIR))
    ? readdirSync(join(ROOT, ABI_DIR), { withFileTypes: true })
        .filter((entry) => entry.isFile() && entry.name.endsWith(".ts"))
        .map((entry) => join(ABI_DIR, entry.name))
        .filter((path) => !expected.has(path))
    : [];
  let drift = false;
  for (const { path, content } of targets) {
    const formatted = format(path, content);
    const full = join(ROOT, path);
    const current = (() => {
      try {
        return readFileSync(full, "utf8");
      } catch {
        return "";
      }
    })();
    if (CHECK) {
      if (current !== formatted) {
        console.error(`gen: ${path} is out of date`);
        drift = true;
      }
    } else if (current !== formatted) {
      writeFileSync(full, formatted);
      console.log(`gen: wrote ${path}`);
    }
  }
  for (const stray of strays) {
    if (CHECK) {
      console.error(`gen: ${stray} is not produced by gen.ts`);
      drift = true;
    } else {
      rmSync(join(ROOT, stray));
      console.log(`gen: deleted stray ${stray}`);
    }
  }
  if (drift) {
    console.error("gen: run `bun run gen` to regenerate");
    process.exitCode = 1;
  }
}
